"""Canonical Protocol v1 Message Definitions.

Defines the core immutable message structures with strict validation and canonical serialization.
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from enum import Enum
import time
from typing import Any, Dict, List, Optional, Union

from .canonical import canonical_json, compute_digest


class CapabilityKind(str, Enum):
    DETERMINISTIC = "deterministic"
    NEURAL_INTERPRETER = "neural_interpreter"
    KNOWLEDGE_BACKED = "knowledge_backed"


class AuthorityLevel(str, Enum):
    PROPOSAL_ONLY = "proposal_only"
    CERTIFIED_DIRECT = "certified_direct"
    SYSTEM_INTERNAL = "system_internal"


class CommitDisposition(str, Enum):
    COMMITTED = "COMMITTED"
    REJECTED = "REJECTED"
    COMPENSATED = "COMPENSATED"
    QUARANTINED = "QUARANTINED"


class QualificationStatus(str, Enum):
    EXPERIMENTAL = "experimental"
    QUALIFIED = "qualified"
    DISQUALIFIED = "disqualified"
    QUARANTINED = "quarantined"


@dataclass(frozen=True)
class ProtocolMessage:
    """Base class for all protocol messages providing canonical digest computation."""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    def to_canonical_json(self) -> str:
        return canonical_json(self.to_dict())

    def digest(self) -> str:
        return compute_digest(self.to_dict())


@dataclass(frozen=True)
class WorkRequest(ProtocolMessage):
    """Canonical Work Request envelope."""
    work_id: str
    origin_node: str
    state_reference: str  # Hash or URI of expected pre-state
    requested_capability: str
    payload: Dict[str, Any]
    deadline_policy: str = "best_effort"  # e.g., "hard:500ms", "best_effort"
    causal_parents: List[str] = field(default_factory=list)
    local_sequence: int = 0
    created_at_utc: float = field(default_factory=time.time)


@dataclass(frozen=True)
class CapabilityDescriptor(ProtocolMessage):
    """Universal descriptor for any registered capability."""
    capability_id: str
    version: str
    kind: CapabilityKind
    input_contract: str
    output_contract: str
    authority_level: AuthorityLevel = AuthorityLevel.PROPOSAL_ONLY
    dependencies: List[str] = field(default_factory=list)
    constraints: Dict[str, Any] = field(default_factory=dict)
    qualification_profile: str = "host-reference"
    qualification_status: QualificationStatus = QualificationStatus.EXPERIMENTAL
    implementation_metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class CapabilityProposal(ProtocolMessage):
    """Unprivileged proposal generated by a learned, deterministic, or knowledge provider."""
    proposal_id: str
    work_id: str
    producer_identity: str
    capability_id: str
    proposed_action: str
    bindings: Dict[str, Any]
    uncertainty_score: float = 0.0
    evidence: Dict[str, Any] = field(default_factory=dict)
    produced_at_utc: float = field(default_factory=time.time)

    def validate_boundary(self) -> bool:
        """Enforces invariant: A proposal cannot declare itself authorized."""
        if "authorized" in self.bindings or "certified" in self.bindings:
            return False
        if "grant_authority" in self.evidence:
            return False
        return True


@dataclass(frozen=True)
class WorkCertificate(ProtocolMessage):
    """Cryptographic authorization certificate issued exclusively by the UoW Authority Kernel."""
    certificate_id: str
    work_id: str
    contract_hash: str
    pre_state_hash: str
    proposed_state_hash: str
    selected_route_index: int
    authorization_evidence: Dict[str, Any]
    issuer_identity: str
    validity_conditions: Dict[str, Any] = field(default_factory=dict)
    is_valid: bool = True
    issued_at_utc: float = field(default_factory=time.time)
    rejection_reason: Optional[str] = None


@dataclass(frozen=True)
class CommitRecord(ProtocolMessage):
    """Immutable ledger entry recording an executed transaction or certified rejection."""
    commit_id: str
    work_id: str
    step_number: int
    prev_evidence_root: str
    resulting_state_hash: str
    disposition: CommitDisposition
    certificate_digest: str
    committed_at_utc: float = field(default_factory=time.time)
    details: Dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class WorkEvent(ProtocolMessage):
    """Distributed event with explicit local ordering and causal dependencies."""
    event_id: str
    node_id: str
    local_sequence: int
    local_time_ms: int
    causal_parents: List[str]
    event_type: str
    payload: Dict[str, Any]


@dataclass(frozen=True)
class RecoveryCommand(ProtocolMessage):
    """Direct compensation and recovery instruction for interrupted or failed work."""
    recovery_id: str
    failed_work_id: str
    permitted_compensation: str
    idempotency_key: str
    target_node: str
    target_state_hash: str
    issued_at_utc: float = field(default_factory=time.time)


@dataclass(frozen=True)
class CapabilityPackageManifest(ProtocolMessage):
    """Manifest for installable capability packages."""
    schema: str = "uow.capability.v1"
    package_id: str = ""
    version: str = "1.0.0"
    name: str = ""
    kind: CapabilityKind = CapabilityKind.DETERMINISTIC
    capabilities: List[CapabilityDescriptor] = field(default_factory=list)
    artifacts: Dict[str, str] = field(default_factory=dict)  # filename -> sha256
    dependencies: List[str] = field(default_factory=list)
    qualification_metadata: Dict[str, Any] = field(default_factory=dict)
    signature: Optional[str] = None
